/**
 * DESIGN SYSTEM GENERATOR - writes docs/DESIGN_SYSTEM.md from src/core/tokens.ts and the theme contract,
 * so no number in the doc can drift (type scale, spacing, grids, zones, contrast ratios, UI scale math).
 *
 * Usage:  npx tsx scripts/gen-design-system.mjs          (write docs/DESIGN_SYSTEM.md)
 *         npx tsx scripts/gen-design-system.mjs --check  (exit 1 if the file is stale)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "docs", "DESIGN_SYSTEM.md");
const CHECK = process.argv.includes("--check");

const T = await import("../src/core/tokens.ts");
const C = await import("../src/core/theme-contract.ts");
const { TYPE_SCALE, MIN_TEXT_PX, SPACE, SURFACE_PADDING, LAYOUT, RADII, STROKES, SHADOWS, UI_SCALE, COLOR_RULES, BROADCAST_SCALE } = T;

const row = (...c) => `| ${c.join(" | ")} |`;
const table = (head, rows) => [row(...head), row(...head.map(() => "---")), ...rows.map((r) => row(...r))];
const out = [];
const push = (...l) => out.push(...l);

/* ---------------- colour maths (WCAG 2.x) ---------------- */
const hex = (h) => {
  const m = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(String(h).trim());
  if (!m) return null;
  const s = m[1].length === 3 ? m[1].split("").map((c) => c + c).join("") : m[1];
  return [0, 2, 4].map((i) => parseInt(s.slice(i, i + 2), 16));
};
const lum = ([r, g, b]) => {
  const f = (v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; };
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
};
const ratio = (a, b) => {
  const A = hex(a), B = hex(b);
  if (!A || !B) return null;
  const [hi, lo] = [lum(A), lum(B)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};
const verdict = (r) => (r === null ? "n/a" : r >= 7 ? "AAA" : r >= 4.5 ? "AA" : r >= 3 ? "large only" : "FAIL");

const MODES = ["light", "dark", "vibrant-brand", "editorial-warm", "kinetic-acid", "technical-drafting"];
const PAIRS = [
  ["textPrimary", "bgPrimary", "Headline / body on canvas"],
  ["textPrimary", "bgSurface", "Text on cards and shells"],
  ["textMuted", "bgPrimary", "Secondary text on canvas"],
  ["textMuted", "bgSurface", "Secondary text on cards"],
  ["textMuted", "bgSurfaceSubtle", "Secondary text on sidebar / alt rows"],
  ["textGhost", "bgSurface", "Meta, timestamps (decorative only)"],
  ["accentPrimary", "bgSurface", "Accent text or icon on card"],
  ["bgSurface", "accentPrimary", "Label on an accent button or finale canvas"],
  ["accentSecondary", "bgSurface", "Secondary accent on card"],
];

/* ---------------- document ---------------- */
const L169 = LAYOUT["16:9"], L916 = LAYOUT["9:16"];
push("# Design system (numbers, not adjectives)", "",
  "> GENERATED by `npx tsx scripts/gen-design-system.mjs` from `src/core/tokens.ts` and `src/core/theme-contract.ts`. Do not edit by hand; `--check` fails when stale.",
  `> All px values are on the FINAL frame: 16:9 = ${L169.width}x${L169.height}, 9:16 = ${L916.width}x${L916.height}. Minimum text on any frame: **${MIN_TEXT_PX} px**.`, "");

/* 1 type */
push("## 1. Type scale", "",
  "Geometric sans for everything except code (mono). Use at most 3 sizes per frame. Headline words are 4-8 per line, never a paragraph.", "");
const width = (a) => LAYOUT[a].width - 2 * LAYOUT[a].marginX;
const rows = [];
for (const k of Object.keys(TYPE_SCALE["16:9"])) {
  const a = TYPE_SCALE["16:9"][k], b = TYPE_SCALE["9:16"][k];
  const chars = (t, asp) => (["display", "headline", "title", "body"].includes(k) ? ` (~${Math.floor(width(asp) / (t.px * 0.5))} chars)` : "");
  rows.push([k, `${a.px} / ${a.lineHeight}`, `${b.px} / ${b.lineHeight}`, a.tracking, a.weight, `${a.wordsPerLine}${chars(a, "16:9")}`, `${b.wordsPerLine}${chars(b, "9:16")}`]);
}
push(...table(["role", "16:9 px / line-height", "9:16 px / line-height", "tracking", "weight", "16:9 max words per line", "9:16 max words per line"], rows), "",
  `Tailwind form: \`text-[72px] font-extrabold tracking-[-0.03em] leading-[1.08]\`. Labels and kickers are uppercase. Chars per line = content width / (px x 0.5); content width is ${width("16:9")} px in 16:9 and ${width("9:16")} px in 9:16. Longer lines must wrap or shrink one step. (Legacy \`BROADCAST_SCALE.typography\` hero ${BROADCAST_SCALE.typography.heroMessage.match(/\[(\d+)px\]/)[1]} px is the old 9:16 preset; prefer this table.)`, "");

/* 2 spacing */
push("## 2. Spacing (8 px grid)", "", ...table(["token", "px"], Object.entries(SPACE).map(([k, v]) => [k, v])), "",
  "Only these values for gap, padding and margin on the final frame. Inside surfaces:", "",
  ...table(["where", "16:9", "9:16"], [
    ["card padding", `${SURFACE_PADDING["16:9"].card}`, `${SURFACE_PADDING["9:16"].card}`],
    ["gap between cards", `${SURFACE_PADDING["16:9"].cardGap}`, `${SURFACE_PADDING["9:16"].cardGap}`],
    ["shell content padding", `${SURFACE_PADDING["16:9"].shell}`, `${SURFACE_PADDING["9:16"].shell}`],
    ["shell header padding", `${SURFACE_PADDING["16:9"].shellHeader}`, `${SURFACE_PADDING["9:16"].shellHeader}`],
    ["pill (y, x)", SURFACE_PADDING["16:9"].pill.join(", "), SURFACE_PADDING["9:16"].pill.join(", ")],
    ["button (y, x)", SURFACE_PADDING["16:9"].button.join(", "), SURFACE_PADDING["9:16"].button.join(", ")],
  ]), "");

/* 3 layout */
push("## 3. Layout grids and safe areas", "");
const area = (a) => {
  const l = LAYOUT[a];
  return { x0: l.marginX, x1: l.width - l.marginX, y0: l.safeTop, y1: l.height - l.safeBottom };
};
const colw = (a) => { const l = LAYOUT[a]; return (l.width - 2 * l.marginX - (l.columns - 1) * l.gutter) / l.columns; };
push(...table(["", "16:9", "9:16"], [
  ["canvas", `${L169.width}x${L169.height}`, `${L916.width}x${L916.height}`],
  ["safe top / bottom (validate-spec min)", `${L169.safeTop} / ${L169.safeBottom}`, `${L916.safeTop} / ${L916.safeBottom}`],
  ["side margin", L169.marginX, L916.marginX],
  ["live area (x0,y0)-(x1,y1)", `(${area("16:9").x0},${area("16:9").y0})-(${area("16:9").x1},${area("16:9").y1})`, `(${area("9:16").x0},${area("9:16").y0})-(${area("9:16").x1},${area("9:16").y1})`],
  ["live size", `${area("16:9").x1 - area("16:9").x0}x${area("16:9").y1 - area("16:9").y0}`, `${area("9:16").x1 - area("9:16").x0}x${area("9:16").y1 - area("9:16").y0}`],
  ["columns x gutter", `${L169.columns} x ${L169.gutter}`, `${L916.columns} x ${L916.gutter}`],
  ["column width", colw("16:9"), colw("9:16")],
]), "");
const colX = (a) => Array.from({ length: LAYOUT[a].columns }, (_, i) => Math.round(LAYOUT[a].marginX + i * (colw(a) + LAYOUT[a].gutter)));
push(`Column left edges, 16:9: ${colX("16:9").join(", ")}. 9:16: ${colX("9:16").join(", ")}. A block spans n columns = n x column width + (n-1) x gutter.`, "",
  "### 3x3 storyboard zones (spec.json `board.zone`), pixel rectangles x,y,w,h inside the live area", "");
const ZN = [["top-left", "top-center", "top-right"], ["middle-left", "middle-center", "middle-right"], ["bottom-left", "bottom-center", "bottom-right"]];
const zrect = (a, r, c) => {
  const { x0, x1, y0, y1 } = area(a), w = (x1 - x0) / 3, h = (y1 - y0) / 3;
  return `${Math.round(x0 + c * w)},${Math.round(y0 + r * h)},${Math.round(w)},${Math.round(h)}`;
};
push(...table(["zone", "16:9 x,y,w,h", "9:16 x,y,w,h"], ZN.flatMap((names, r) => names.map((n, c) => [n, zrect("16:9", r, c), zrect("9:16", r, c)]))), "",
  "Aliases: `center` = middle-center, `top` = top-center, `bottom` = bottom-center, `left` = middle-left, `right` = middle-right.", "");

/* 4 colour */
push("## 4. Colour: palettes, contrast, accent rules", "",
  `Never hardcode hex in a Scene: read \`getTheme(mode).colors\`. **Max ${COLOR_RULES.maxAccentsPerFrame} accents per frame** (primary accent plus at most one secondary covering <= ${COLOR_RULES.secondaryAccentMaxAreaPct}% of the area). Status colors (success, warning, danger) only for real status. No neon glow, no gradient text. WCAG ratios below are computed from the theme hex values; use only AA or better for text under 24 px, "large only" needs >= 24 px bold.`, "");
for (const mode of MODES) {
  const th = C.getTheme(mode), c = th.colors;
  push(`### ${mode}`, "",
    `bgPrimary \`${c.bgPrimary}\`, bgSurface \`${c.bgSurface}\`, bgSurfaceSubtle \`${c.bgSurfaceSubtle}\`, textPrimary \`${c.textPrimary}\`, textMuted \`${c.textMuted}\`, textGhost \`${c.textGhost}\`, accentPrimary \`${c.accentPrimary}\`, accentSecondary \`${c.accentSecondary}\`; status \`${c.statusSuccess}\` / \`${c.statusWarning}\` / \`${c.statusDanger}\`; radii ${th.geometry.radiusSm}/${th.geometry.radiusMd}/${th.geometry.radiusLg}.`, "",
    ...table(["text on background", "use", "ratio", "grade"], PAIRS.map(([f, b, use]) => {
      const r = ratio(c[f], c[b]);
      return [`${f} on ${b}`, use, r === null ? "-" : r.toFixed(2), verdict(r)];
    })), "");
}

/* 5 UI at broadcast scale */
push("## 5. UI at broadcast scale", "",
  `A desktop UI drawn at native web size (body 14-16 px) is unreadable when the whole window is shown on a ${L169.width}x${L169.height} frame. Rule: **scale factor = ${MIN_TEXT_PX} / native font px**, and crop or zoom the UI until every text is at least ${MIN_TEXT_PX} px on screen.`, "",
  `Primitives in \`src/primitives\` draw their smallest labels at ${UI_SCALE.widgetNativeLabelPx} px native: wrap them in \`style={{ zoom: ${UI_SCALE.recommendedZoom[0]} to ${UI_SCALE.recommendedZoom[1]} }}\` (min ${(MIN_TEXT_PX / UI_SCALE.widgetNativeLabelPx).toFixed(3)}). Never reduce type instead of cropping.`, "",
  ...table(["native font px", "scale needed", "native crop width for 16:9", "native crop width for 9:16"],
    [11, 12, 13, 14, 16, 18].map((n) => { const s = MIN_TEXT_PX / n; return [n, s.toFixed(3), Math.floor(L169.width / s), Math.floor(L916.width / s)]; })), "",
  "Crop a native window of width W to the full frame: scale = frame width / W. Typical crops:", "",
  ...table(["native crop W", "scale to 1920 (16:9)", "14 px body becomes", "12 px label becomes", "ok?"],
    [1920, 1600, 1440, 1280, 1100, 960].map((w) => { const s = L169.width / w; return [w, s.toFixed(2), `${(14 * s).toFixed(1)} px`, `${(12 * s).toFixed(1)} px`, 14 * s >= MIN_TEXT_PX && 12 * s >= MIN_TEXT_PX ? "yes" : 14 * s >= MIN_TEXT_PX ? "body only" : "no"]; })), "",
  "In 9:16 (1080 wide) a 390 px mobile screen scales x2.77 (14 px becomes 38.8 px); a 1440 px desktop crop needs a 760 px native crop (x1.42) to keep 14 px text at 20 px.", "",
  "Practical recipe: build the UI at a native 960-1280 px wide, give the wrapper `zoom`, show 3-5 rows or cards (not 12), and let the camera push in on the focal control. Show one idea per beat.", "");

/* 6 radii shadows strokes */
push("## 6. Radii, strokes, shadows", "",
  ...table(["radius", "px", "use"], [["sm", RADII.sm, "chips, inputs, small buttons"], ["md", RADII.md, "cards, buttons"], ["lg", RADII.lg, "shells, modals, large cards"], ["xl", RADII.xl, "hero cards, device bezels"], ["pill", RADII.pill, "pills, CTA buttons"]]), "",
  ...table(["stroke", "px", "use"], [["hairline", STROKES.hairline, "borders, table rules, grid lines (rgba 0.07-0.14 white on dark)"], ["default", STROKES.default, "icons, chart axes"], ["emphasis", STROKES.emphasis, "chart lines, focus rings, underlines"], ["specularRim", STROKES.specularRim, "1px top highlight on dark cards"]]), "",
  ...table(["elevation", "light surfaces", "dark surfaces"], ["e1", "e2", "e3"].map((k) => [k, `\`${SHADOWS.light[k]}\``, `\`${SHADOWS.dark[k]}\``])), "",
  "e1 cards in a row, e2 tables, e3 shells and modals. Shadows are black or slate only, never colored.", "");

fs.mkdirSync(path.dirname(OUT), { recursive: true });
const text = out.join("\n") + "\n";
if (CHECK) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf-8") : "";
  if (cur !== text) { console.error("docs/DESIGN_SYSTEM.md is stale: run `npx tsx scripts/gen-design-system.mjs`"); process.exit(1); }
  console.log("docs/DESIGN_SYSTEM.md is up to date");
} else {
  fs.writeFileSync(OUT, text);
  console.log(`wrote docs/DESIGN_SYSTEM.md (${out.length} lines)`);
}
